// Builds server/src/dining/chains-data.ts: restaurant, fast-food, café and ice-cream brand names from
// OpenStreetMap's name-suggestion-index (NSI, BSD-3-Clause, https://github.com/osmlab/name-suggestion-index).
//
//   npm pack name-suggestion-index && tar xzf name-suggestion-index-*.tgz
//   npx tsx scripts/build-chains.ts package/dist/json/nsi.json
//
// Each line is "normalized name|country codes" (001 = worldwide), so a brand known only in, say, Japan
// isn't flagged as a chain in the US.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { normalizeBrand } from "../server/src/dining/chains.js";

const file = process.argv[2];
if (!file) {
  console.error("Usage: npx tsx scripts/build-chains.ts path/to/nsi.json");
  process.exit(1);
}

interface Item {
  displayName: string;
  locationSet?: { include?: string[] };
  matchNames?: string[];
  tags: Record<string, string>;
}
const data = JSON.parse(fs.readFileSync(file, "utf8")) as { _meta?: { version?: string }; nsi: Record<string, { items: Item[] }> };
const groups = ["brands/amenity/restaurant", "brands/amenity/fast_food", "brands/amenity/cafe", "brands/amenity/ice_cream"];

const byName = new Map<string, Set<string>>();
for (const g of groups) {
  for (const item of data.nsi[g]?.items ?? []) {
    const countries = (item.locationSet?.include ?? ["001"]).map((c) => String(c).toLowerCase()).filter((c) => /^[a-z]{2}$|^001$/.test(c));
    const names = [item.displayName, item.tags.brand, item.tags.name, item.tags["name:en"], ...(item.matchNames ?? [])];
    for (const n of names) {
      const key = n ? normalizeBrand(n) : "";
      // One- or two-letter names match too much by accident.
      if (key.length < 3) continue;
      const set = byName.get(key) ?? new Set<string>();
      for (const c of countries.length ? countries : ["001"]) set.add(c);
      byName.set(key, set);
    }
  }
}

const lines = [...byName.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([n, cs]) => `${n}|${[...cs].sort().join(",")}`);
const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "../server/src/dining/chains-data.ts");
fs.writeFileSync(
  out,
  `// Generated by scripts/build-chains.ts from name-suggestion-index ${data._meta?.version ?? ""} (BSD-3-Clause,\n` +
    `// Copyright name-suggestion-index contributors). Do not edit by hand.\n` +
    `// "normalized brand name|country codes" (001 = worldwide).\n` +
    `export const CHAIN_LINES = ${JSON.stringify(lines.join("\n"))};\n`,
);
console.log(`Wrote ${lines.length} brand names to ${out}`);
